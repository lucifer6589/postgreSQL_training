CREATE DATABASE social_db;

CREATE TABLE users(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(100) NOT NULL
);

CREATE TABLE friends(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id INT NOT NULL REFERENCES users(id),
CONSTRAINT fk_friends_user
FOREIGN KEY (user_id) REFERENCES users(id),
CONSTRAINT fk_friends_friend
FOREIGN KEY (friend_id) REFERENCES users(id),
CONSTRAINT uq_friends_user_id_friend_id
UNIQUE (user_id, friend_id),
CONSTRAINT chk_self_friend
CHECK (user_id <> friend_id)
);

CREATE TABLE images(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
image_user INT NOT NULL REFERENCES users(id),
filename VARCHAR(100) NOT NULL
);

CREATE TABLE tags(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
image_id INT NOT NULL REFERENCES images(id),
tagged_user INT NOT NULL REFERENCES users(id),
CONSTRAINT uq_tags_image_user
UNIQUE (image_id, tagged_user)
);

CREATE INDEX idx_friends_user_id_friend_id
ON friends(user_id, friend_id);
CREATE INDEX idx_friends_friend_id_user_id
ON friends(friend_id, user_id);

CREATE INDEX idx_images_image_user
ON images(image_user);

CREATE INDEX idx_tags_tagged_user
ON tags(tagged_user);



