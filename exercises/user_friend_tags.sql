 -- 3. friends who tagged in all images
 SELECT f.user_id,f.friend_id
 FROM friends f
 JOIN images i
 on f.friend_id = i.image_user
 LEFT JOIN tags t
 ON t.image_id = i.id
 AND f.user_id = t.tagged_user
 WHERE f.user_id = 1
 GROUP BY f.user_id, f.friend_id
 HAVING COUNT(i.id) = COUNT(t.image_id);
