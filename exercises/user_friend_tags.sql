CREATE TABLE users(
id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(100) NOT NULL
);

CREATE TABLE friends(
user_id INT NOT NULL REFERENCES users(id),
friend_id INT NOT NULL REFERENCES users(id),
created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
PRIMARY KEY (user_id, friend_id)
);

CREATE TABLE images(
id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
image_user INT NOT NULL REFERENCES users(id),
filename VARCHAR(100) NOT NULL
);

CREATE TABLE tags(
image_id INT NOT NULL REFERENCES images(id),
tagged_user INT NOT NULL REFERENCES users(id),
PRIMARY KEY(image_id, tagged_user)
);


CREATE INDEX idx_friends_friend_id_user_id
ON friends(friend_id, user_id);

CREATE INDEX idx_images_image_user
ON images(image_user);

CREATE INDEX idx_tags_tagged_user
ON tags(tagged_user);


