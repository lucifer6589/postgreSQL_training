 -- 4. friend who tagged the most
 SELECT user_id, friend_id, tag_count
 FROM (
 SELECT f.user_id,f.friend_id, COUNT(*) AS tag_count,
 RANK() OVER (ORDER BY COUNT(*) DESC) AS rnk
 FROM friends f
 JOIN images i
 on f.friend_id = i.image_user
 JOIN tags t
 ON t.image_id = i.id
