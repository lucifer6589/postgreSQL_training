-- Write a query to select article which has maximum comments
 SELECT a.title, COUNT(c.id) AS comments_count
 FROM articles a
 LEFT JOIN comments c
 ON c.article_id = a.id
 GROUP BY a.id
 ORDER BY comments_count DESC
 LIMIT 1;
