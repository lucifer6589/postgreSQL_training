-- Which city were the maximum respondents from?
SELECT c.name AS city, COUNT(s.id) AS no_of_responses
FROM cities c
JOIN subscribers s 
ON c.id = s.city_id
GROUP BY c.id
ORDER BY no_of_responses DESC
LIMIT 1;

