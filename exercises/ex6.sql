-- how many people responded from each city
SELECT city, COUNT(*) AS no_of_responses
 FROM subscribers
 GROUP BY city;
   city    | no_of_responses
-----------+-----------------
  Chennai  |              42
  Lucknow  |              39
  Delhi    |              40
  Kolkatta |              38
  Mumbai   |              41
(5 rows)



-- city with maximum respondents
SELECT city, COUNT(*) AS no_of_responses
 FROM subscribers
 GROUP BY city
 HAVING COUNT(*) = (SELECT COUNT(*) AS no_of_responses
 FROM subscribers
 GROUP BY city
 ORDER BY no_of_responses DESC
 LIMIT 1);
   city   | no_of_responses
----------+-----------------
  Chennai |              42
(1 row)


