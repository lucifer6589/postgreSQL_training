CREATE DATABASE subscribers;

CREATE TABLE subscribers(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
email VARCHAR(100),
phone VARCHAR(10),
city VARCHAR(50)
);

COPY subscribers(email, phone, city) FROM 'D:\downloads D\email_subscribers.txt' WITH (FORMAT CSV);

-- which city people responded from
SELECT DISTINCT city
 FROM subscribers;
   city
