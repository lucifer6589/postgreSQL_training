CREATE DATABASE messaging_db;

-- user table 
CREATE TABLE users(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(100) NOT NULL,
email VARCHAR(100) NOT NULL UNIQUE,
hash_password VARCHAR(100) NOT NULL,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- messages table
CREATE TABLE messages(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
sender_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
content TEXT NOT NULL,
sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- thread table 
CREATE TABLE threads(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_one_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
user_two_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
user_one_deleted_at TIMESTAMP,
user_two_deleted_at TIMESTAMP,
created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
CHECK (receiver_id <> sender_id)
);

-- thread messages
CREATE TABLE thread_messages(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
thread_id BIGINT NOT NULL REFERENCES threads(id) ON DELETE CASCADE,
message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
receiver_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
is_read BOOLEAN NOT NULL DEFAULT FALSE,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
UNIQUE(thread_id, message_id)
);

-- indexes 
CREATE INDEX idx_threads_receiver 
ON threads(user_two_id);
CREATE INDEX idx_threads_sender 
ON threads(user_one_id);
CREATE INDEX idx_thread_messages_reciever_id_is_read 
ON thread_messages(receiver_id, is_read);
CREATE INDEX idx_thread_messages_thread_id
ON thread_messages(thread_id);
CREATE INDEX idx_thread_messages_message
ON thread_messages(message_id);
CREATE INDEX idx_messages_sent_at
ON messages(sent_at);


