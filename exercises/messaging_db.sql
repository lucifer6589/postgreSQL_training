CREATE DATABASE messaging_db_v2;

-- user table 
CREATE TABLE users(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(100) NOT NULL,
email VARCHAR(100) NOT NULL UNIQUE,
hash_password VARCHAR(100) NOT NULL,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- messages table
CREATE TABLE messages(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
sender_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
parent_message_id BIGINT REFERENCES messages(id) ON DELETE CASCADE,
content TEXT NOT NULL,
sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- message_receivers table
CREATE TABLE message_receivers(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
receiver_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
read_at TIMESTAMP,
deleted_at TIMESTAMP,
UNIQUE(message_id, receiver_id)
);

-- indexes 
CREATE INDEX idx_messages_sender 
ON messages(sender_id);

CREATE INDEX idx_messages_parent 
ON messages(parent_message_id);

CREATE INDEX idx_messages_sent_at 
ON messages(sent_at);

CREATE INDEX idx_message_receivers_inbox 
ON message_receivers(receiver_id, deleted_at, read_at);

CREATE INDEX idx_message_receivers_message 
ON message_receivers(message_id);


