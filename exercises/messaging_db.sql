-- inbox of a user
SELECT t.id AS thread_id, u.name AS from_user, m.content, tm.is_read, m.sent_at
FROM thread_messages tm
JOIN threads t ON tm.thread_id = t.id
JOIN messages m ON tm.message_id = m.id
LEFT JOIN users u ON m.sender_id = u.id
WHERE tm.receiver_id = 2
